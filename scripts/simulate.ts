/**
 * Simulates 60 rounds of each scenario with scripted keepers (no chain, no LLM)
 * and writes data/simulation.json and SIMULATION.md.
 *
 *   pnpm simulate
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SCENARIOS, TESTNET_PARAMS, fmt, simulate } from "@nearhearth/hearth";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ROUNDS = 60;
const results = SCENARIOS.map((sc) => ({ ...simulate(TESTNET_PARAMS, sc, ROUNDS), title: sc.title, description: sc.description }));
writeFileSync(join(root, "data", "simulation.json"), `${JSON.stringify({ rounds: ROUNDS, params: "TESTNET_PARAMS", results }, null, 1)}\n`);

const n = (x: number) => x.toLocaleString("en-US", { maximumFractionDigits: 0 });
const lines = [
  "# Simulation: 60 rounds, four communities",
  "",
  "Generated by `pnpm simulate` from `packages/hearth/src/sim.ts`, with the rules and parameters the contract launches with (`RULES.md`). Scripted keepers, a fixed random seed, no chain and no LLM, so every run prints the same numbers.",
  "",
  `Line at streak 0: ${fmt(TESTNET_PARAMS.baseLine)} EMBER, rising 10% per streak level to 3×. Spark pool: 150% of the line. Ash: 50% of pledges when the fire goes out. Treasury burn: 2% per round that goes out.`,
  "",
  "| Scenario | Roared | Out | Cold | Best streak | Burned | Minted as sparks | Supply after 60 rounds | Treasury after 60 rounds |",
  "|---|---|---|---|---|---|---|---|---|",
  ...results.map(
    (r) =>
      `| ${r.title} | ${r.summary.roared} | ${r.summary.out} | ${r.summary.cold} | ${r.summary.bestStreak} | ${n(r.summary.burned)} | ${n(r.summary.minted)} | ${r.summary.supplyChangePct > 0 ? "+" : ""}${r.summary.supplyChangePct}% | ${r.summary.treasuryChangePct}% |`,
  ),
  "",
];
for (const r of results) {
  lines.push(`## ${r.title}`, "", r.description, "", "| Round | Line | Pledged | Outcome | Streak | Supply | Treasury |", "|---|---|---|---|---|---|---|");
  for (const row of r.rows.filter((x) => x.round % 6 === 5 || x.round < 3))
    lines.push(`| ${row.round} | ${n(row.line)} | ${n(row.pledged)} | ${row.outcome} | ${row.streak} | ${n(row.supply)} | ${n(row.treasury)} |`);
  lines.push("");
}
lines.push(
  "## What we took from it",
  "",
  "- **Coordination is the whole game.** The same steady crowd that keeps the fire roaring with three closers fails often without them. Closers turn a crowd into a swarm.",
  "- **Over-pledging is deflationary.** The overeager crowd keeps the fire lit but burns more than the fixed spark pool mints back, so supply shrinks and each pledger loses on every round.",
  "- **A dying community drains the treasury, slowly.** Each round that goes out burns 2% of it. That is the stake the memecoin puts on the table.",
  "- These results set the launch parameters: a 150% spark pool rewards landing the line, and 50% ash makes a failed round hurt without wiping pledgers out.",
  "",
);
writeFileSync(join(root, "SIMULATION.md"), lines.join("\n"));
for (const r of results) console.log(r.scenario.padEnd(12), JSON.stringify(r.summary));
